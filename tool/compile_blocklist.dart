import 'dart:io';

/// Merges the curated list, vendor EasyList-style snapshots, and exclusions
/// into [assets/rules/tracker_domains.txt]. The app never runs this.
void main() {
  final root = Directory.current;
  final curated = File('assets/rules/tracker_domains.curated.txt');
  final exclusionsFile = File('assets/rules/blocklist_exclusions.txt');
  final vendorDir = Directory('assets/rules/vendor');
  final out = File('assets/rules/tracker_domains.txt');

  if (!curated.existsSync()) {
    stderr.writeln('Missing ${curated.path}');
    exitCode = 1;
    return;
  }

  final exclusions = _readHosts(exclusionsFile);
  final byCategory = <String, Set<String>>{
    'advertising': {},
    'analytics': {},
    'attribution': {},
    'profiling': {},
  };

  _ingestCurated(curated, byCategory, exclusions);
  final priority = {
    for (final category in byCategory.keys) ...byCategory[category]!,
  };
  if (vendorDir.existsSync()) {
    for (final file in vendorDir.listSync().whereType<File>()) {
      final name = file.uri.pathSegments.last.toLowerCase();
      if (!name.endsWith('.txt') || name.startsWith('readme')) continue;
      final category = name.contains('privacy') || name.contains('analytic')
          ? 'analytics'
          : name.contains('attribut')
          ? 'attribution'
          : name.contains('profil')
          ? 'profiling'
          : 'advertising';
      _ingestVendor(file, category, byCategory, exclusions);
    }
  }

  const cap = 15000;
  final selected = <String, List<String>>{
    for (final category in byCategory.keys) category: [],
  };
  var total = 0;
  for (final category in byCategory.keys) {
    final hosts = byCategory[category]!.toList()..sort();
    for (final host in hosts) {
      if (!priority.contains(host)) continue;
      selected[category]!.add(host);
      total++;
    }
  }
  final remainders = <String, List<String>>{
    for (final category in byCategory.keys)
      category:
          (byCategory[category]!
              .difference(selected[category]!.toSet())
              .toList()
            ..sort()),
  };
  final offsets = {for (final category in byCategory.keys) category: 0};
  var progressed = true;
  while (total < cap && progressed) {
    progressed = false;
    for (final category in byCategory.keys) {
      if (total >= cap) break;
      final pool = remainders[category]!;
      final offset = offsets[category]!;
      if (offset >= pool.length) continue;
      selected[category]!.add(pool[offset]);
      offsets[category] = offset + 1;
      total++;
      progressed = true;
    }
  }

  final lines = <String>[];
  for (final category in selected.keys) {
    final hosts = selected[category]!;
    if (hosts.isEmpty) continue;
    lines.add('');
    lines.add('# $category');
    for (final host in hosts) {
      lines.add('$host $category');
    }
  }

  final header = StringBuffer()
    ..writeln('# version: 2026.10.2')
    ..writeln(
      '# Privacy Lens tracker domain list. Generated by tool/compile_blocklist.dart.',
    )
    ..writeln('# One `domain category` per line. A listed domain also blocks')
    ..writeln('# its subdomains. Do not fetch this file at runtime.')
    ..writeln('#')
    ..writeln('# Sources (vendored snapshots, not live downloads):')
    ..writeln('# - assets/rules/tracker_domains.curated.txt')
    ..writeln(
      '# - EasyList / EasyPrivacy ||domain^ hosts (GPLv3 / CC BY-SA 3.0)',
    )
    ..writeln('# - extra mobile advertising and analytics hosts')
    ..writeln('# Exclusions: assets/rules/blocklist_exclusions.txt');

  out.writeAsStringSync('${header.toString()}${lines.join('\n')}\n');
  stdout.writeln('Wrote $total hosts to ${out.path} from ${root.path}');
}

void _ingestCurated(
  File file,
  Map<String, Set<String>> byCategory,
  Set<String> exclusions,
) {
  for (final raw in file.readAsLinesSync()) {
    final line = raw.trim();
    if (line.isEmpty || line.startsWith('#')) continue;
    final parts = line.split(RegExp(r'\s+'));
    if (parts.length < 2) continue;
    final host = _normalize(parts.first);
    final category = parts[1];
    if (host == null || !byCategory.containsKey(category)) continue;
    _offer(host, category, byCategory, exclusions);
  }
}

void _ingestVendor(
  File file,
  String category,
  Map<String, Set<String>> byCategory,
  Set<String> exclusions,
) {
  final filter = RegExp(
    r'^\|\|([a-z0-9][a-z0-9.-]*[a-z0-9])\^',
    caseSensitive: false,
  );
  final hostsLine = RegExp(
    r'^(?:0\.0\.0\.0|127\.0\.0\.1)\s+([a-z0-9.-]+)$',
    caseSensitive: false,
  );
  for (final raw in file.readAsLinesSync()) {
    final line = raw.trim();
    if (line.isEmpty || line.startsWith('!') || line.startsWith('[')) continue;
    var host = _normalize(filter.firstMatch(line)?.group(1));
    host ??= _normalize(hostsLine.firstMatch(line)?.group(1));
    if (line.contains(' ') &&
        !line.startsWith('|') &&
        !line.startsWith('0.') &&
        !line.startsWith('127.')) {
      final parts = line.split(RegExp(r'\s+'));
      host ??= _normalize(parts.first);
    }
    if (host == null) continue;
    _offer(host, category, byCategory, exclusions);
  }
}

void _offer(
  String host,
  String category,
  Map<String, Set<String>> byCategory,
  Set<String> exclusions,
) {
  if (_tooBroad.contains(host) ||
      _excluded(host, exclusions) ||
      _alreadyListed(host, byCategory) ||
      _covered(host, byCategory)) {
    return;
  }
  byCategory[category]!.add(host);
}

bool _alreadyListed(String host, Map<String, Set<String>> byCategory) {
  for (final bucket in byCategory.values) {
    if (bucket.contains(host)) return true;
  }
  return false;
}

bool _covered(String host, Map<String, Set<String>> byCategory) {
  var candidate = host;
  while (true) {
    final dot = candidate.indexOf('.');
    if (dot < 0) return false;
    candidate = candidate.substring(dot + 1);
    for (final bucket in byCategory.values) {
      if (bucket.contains(candidate)) return true;
    }
  }
}

Set<String> _readHosts(File file) {
  if (!file.existsSync()) return {};
  return {
    for (final raw in file.readAsLinesSync())
      if (_normalize(raw) case final host?) host,
  };
}

String? _normalize(String? raw) {
  if (raw == null) return null;
  var host = raw.trim().toLowerCase();
  if (host.startsWith('#')) return null;
  host = host.replaceAll(RegExp(r'\.$'), '');
  if (host.contains('/') || host.contains('*') || host.contains(':')) {
    return null;
  }
  if (!RegExp(
    r'^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$',
  ).hasMatch(host)) {
    return null;
  }
  return host;
}

const _tooBroad = {
  'google.com',
  'www.google.com',
  'facebook.com',
  'www.facebook.com',
  'web.facebook.com',
  'yahoo.com',
  't.co',
  'twitter.com',
  'x.com',
  'instagram.com',
  'whatsapp.com',
  'apple.com',
  'microsoft.com',
  'amazon.com',
  'tiktok.com',
};

bool _excluded(String host, Set<String> exclusions) {
  for (final excluded in exclusions) {
    if (host == excluded ||
        host.endsWith('.$excluded') ||
        excluded.endsWith('.$host')) {
      return true;
    }
  }
  return false;
}
